import time

def func():
    print("woshibisongxin")
    time.sleep(3) #这是同步操作，让当前的线程处于阻塞状态，cpu不为我工作
    print("woshibisongxin2")

if __name__ == '__main__':
    func()

# I/O阻塞状态（输入和输出）
# input()程序处于阻塞状态
# requests.get() 在网络请求返回数据之前，程序处于阻塞状态
# 一般情况下，当程序处于IO操作（输入和输出）时，线程会处于阻塞状态

# 协程：当程序遇到IO操作时，可以选择性的切换到其他任务上。
# 在微观上是一个任务一个任务的进行切换，切换条件一般是IO操作
# 在宏观上，我们可以看到的其实是多个任务一起在执行(多任务异步操作)
# 上方的一切都是，都是在单线程的条件下

